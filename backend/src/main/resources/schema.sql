CREATE TABLE IF NOT EXISTS users (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  username TEXT NOT NULL UNIQUE,
  password_salt TEXT NOT NULL,
  password_hash TEXT NOT NULL,
  display_name TEXT NOT NULL,
  role TEXT NOT NULL CHECK (role IN ('QUALITY_INSPECTOR', 'LINE_SUPERVISOR', 'QUALITY_MANAGER', 'AUDITOR')),
  enabled BOOLEAN NOT NULL DEFAULT TRUE,
  created_at TIMESTAMPTZ NOT NULL DEFAULT now()
);

CREATE TABLE IF NOT EXISTS work_order (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  order_no TEXT NOT NULL UNIQUE,
  product_code TEXT NOT NULL,
  product_name TEXT NOT NULL,
  planned_qty NUMERIC(18, 3) NOT NULL CHECK (planned_qty > 0),
  line_code TEXT NOT NULL,
  start_at TIMESTAMPTZ,
  status TEXT NOT NULL DEFAULT 'PLANNED' CHECK (status IN ('PLANNED', 'RUNNING', 'PAUSED', 'FINISHED', 'CANCELLED')),
  created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
  updated_at TIMESTAMPTZ NOT NULL DEFAULT now()
);

CREATE TABLE IF NOT EXISTS product_batch (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  batch_no TEXT NOT NULL UNIQUE,
  work_order_id BIGINT NOT NULL REFERENCES work_order(id),
  quantity NUMERIC(18, 3) NOT NULL CHECK (quantity > 0),
  material_lot_no TEXT NOT NULL,
  produced_at TIMESTAMPTZ,
  batch_status TEXT NOT NULL DEFAULT 'CREATED' CHECK (batch_status IN ('CREATED', 'MATERIAL_ISSUED', 'IN_PROGRESS', 'PASSED', 'CONDITIONAL_PASS', 'RECHECK', 'ON_HOLD', 'BLOCKED', 'RELEASED', 'CLOSED')),
  created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
  updated_at TIMESTAMPTZ NOT NULL DEFAULT now()
);
CREATE INDEX IF NOT EXISTS idx_product_batch_work_order ON product_batch(work_order_id);

CREATE TABLE IF NOT EXISTS quality_inspection (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  batch_id BIGINT NOT NULL REFERENCES product_batch(id),
  inspector_id BIGINT NOT NULL REFERENCES users(id),
  inspection_type TEXT NOT NULL CHECK (inspection_type IN ('FIRST', 'PATROL', 'FINAL')),
  standard_version TEXT NOT NULL,
  result_status TEXT NOT NULL CHECK (result_status IN ('PASS', 'FAIL', 'CONDITIONAL_PASS', 'RECHECK')),
  previous_batch_status TEXT NOT NULL,
  received_batch_quantity NUMERIC(18, 3) NOT NULL,
  inspected_at TIMESTAMPTZ NOT NULL DEFAULT now(),
  created_at TIMESTAMPTZ NOT NULL DEFAULT now()
);
CREATE INDEX IF NOT EXISTS idx_quality_inspection_batch ON quality_inspection(batch_id, inspected_at, id);

CREATE TABLE IF NOT EXISTS inspection_item_result (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  inspection_id BIGINT NOT NULL REFERENCES quality_inspection(id) ON DELETE CASCADE,
  item_code TEXT NOT NULL,
  item_name TEXT NOT NULL,
  measured_value NUMERIC(18, 6) NOT NULL,
  limit_min NUMERIC(18, 6) NOT NULL,
  limit_max NUMERIC(18, 6) NOT NULL,
  item_status TEXT NOT NULL CHECK (item_status IN ('PASS', 'FAIL', 'CONDITIONAL_PASS', 'RECHECK')),
  created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
  UNIQUE (inspection_id, item_code),
  CHECK (limit_min <= limit_max)
);
CREATE INDEX IF NOT EXISTS idx_inspection_item_inspection ON inspection_item_result(inspection_id);

CREATE TABLE IF NOT EXISTS defect_record (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  batch_id BIGINT NOT NULL REFERENCES product_batch(id),
  defect_type TEXT NOT NULL,
  defect_qty NUMERIC(18, 3) NOT NULL CHECK (defect_qty > 0),
  severity TEXT NOT NULL CHECK (severity IN ('MINOR', 'MAJOR', 'CRITICAL')),
  root_cause TEXT NOT NULL,
  original_disposition TEXT NOT NULL DEFAULT 'OPEN',
  disposition_status TEXT NOT NULL DEFAULT 'OPEN' CHECK (disposition_status IN ('OPEN', 'IN_DISPOSITION', 'REWORK', 'SCRAP', 'CONCESSION', 'RETURN_TO_SUPPLIER', 'CLOSED')),
  registered_at TIMESTAMPTZ NOT NULL DEFAULT now(),
  closed_at TIMESTAMPTZ,
  created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
  updated_at TIMESTAMPTZ NOT NULL DEFAULT now()
);
CREATE INDEX IF NOT EXISTS idx_defect_record_batch ON defect_record(batch_id, registered_at, id);

CREATE TABLE IF NOT EXISTS status_event (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  entity_type TEXT NOT NULL CHECK (entity_type IN ('WORK_ORDER', 'BATCH', 'DEFECT')),
  entity_id BIGINT NOT NULL,
  event_type TEXT NOT NULL,
  from_status TEXT,
  to_status TEXT NOT NULL,
  event_payload JSONB NOT NULL DEFAULT '{}'::jsonb,
  actor TEXT NOT NULL,
  occurred_at TIMESTAMPTZ NOT NULL DEFAULT now()
);
CREATE INDEX IF NOT EXISTS idx_status_event_entity ON status_event(entity_type, entity_id, occurred_at, id);

CREATE TABLE IF NOT EXISTS audit_log (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  actor TEXT,
  action TEXT NOT NULL,
  target_type TEXT NOT NULL,
  target_id TEXT NOT NULL,
  message TEXT NOT NULL,
  request_path TEXT,
  request_method TEXT,
  created_at TIMESTAMPTZ NOT NULL DEFAULT now()
);
CREATE INDEX IF NOT EXISTS idx_audit_log_target ON audit_log(target_type, target_id, created_at);

